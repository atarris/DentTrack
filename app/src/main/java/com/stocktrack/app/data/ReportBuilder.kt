package com.stocktrack.app.data

import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/**
 * Sheet and column names of the Excel storage report. The very same file is used for backups,
 * and [BackupCodec] reads these names back when restoring, so change them in one place only.
 */
object ReportFormat {
    const val SHEET_SUMMARY = "Summary"
    const val SHEET_STOCK = "Stock"
    const val SHEET_LOW = "Low stock"
    const val SHEET_LOG = "Activity log"
    const val SHEET_USERS = "Users"
    const val SHEET_CATEGORIES = "Categories"

    /** The backup file keeps at most this many activity log entries (newest first). */
    const val MAX_LOG_ROWS = 999

    // Stock sheet
    const val H_ITEM = "Item"
    const val H_SKU = "SKU / Barcode"
    const val H_CATEGORY = "Category"
    const val H_LOCATION = "Location"
    const val H_UNIT = "Unit"
    const val H_QTY = "Quantity"
    const val H_OWN_ALERT = "Item alert level"
    const val H_USED_ALERT = "Alert level used"
    const val H_STATUS = "Status"
    const val H_COST = "Unit cost"
    const val H_VALUE = "Stock value"
    const val H_NOTE = "Note"
    const val H_ITEM_ID = "Item ID"
    const val H_CREATED = "Created"

    // Activity log sheet (also uses H_ITEM, H_NOTE, H_ITEM_ID)
    const val H_WHEN = "Date / time"
    const val H_USER = "User"
    const val H_ACTION = "Action"
    const val H_CHANGE = "Change"
    const val H_AFTER = "Quantity after"

    /** Fixed pattern and locale so the dates can always be read back. */
    fun dateFormat(): SimpleDateFormat = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.US)
}

/** Builds the Excel storage report (also used as the backup file). */
object ReportBuilder {

    fun build(
        items: List<Item>,
        log: List<LogEntry>,
        users: List<User>,
        generatedBy: String,
        threshold: Int,
        categories: List<String> = emptyList()
    ): ByteArray {
        val fmt = ReportFormat.dateFormat()
        fun status(i: Item) = when {
            i.isOut() -> "OUT OF STOCK"
            i.isLow(threshold) -> "LOW"
            else -> "OK"
        }

        // 1) Summary
        val summary = XlsxWriter.Sheet(
            name = ReportFormat.SHEET_SUMMARY,
            headers = listOf("Metric", "Value"),
            rows = listOf(
                listOf("Report", "DentTrack storage report"),
                listOf("Report generated", fmt.format(Date())),
                listOf("Generated by", generatedBy),
                listOf("Total items", items.size),
                listOf("Activity log rows in this file", minOf(log.size, ReportFormat.MAX_LOG_ROWS)),
                listOf("Total units in stock", items.sumOf { it.quantity.toLong() }),
                listOf("Low stock items", items.count { it.isLow(threshold) }),
                listOf("Out of stock items", items.count { it.isOut() }),
                listOf("Global low stock threshold", threshold),
                listOf("Total stock value", items.sumOf { it.stockValue() })
            ),
            widths = listOf(28, 28)
        )

        // 2) Full stock list
        val stockSorted = items.sortedBy { it.name.lowercase() }
        val stock = XlsxWriter.Sheet(
            name = ReportFormat.SHEET_STOCK,
            headers = listOf(
                ReportFormat.H_ITEM, ReportFormat.H_SKU, ReportFormat.H_CATEGORY, ReportFormat.H_LOCATION,
                ReportFormat.H_UNIT, ReportFormat.H_QTY, ReportFormat.H_OWN_ALERT, ReportFormat.H_USED_ALERT,
                ReportFormat.H_STATUS, ReportFormat.H_COST, ReportFormat.H_VALUE, ReportFormat.H_NOTE,
                ReportFormat.H_ITEM_ID, ReportFormat.H_CREATED
            ),
            rows = stockSorted.map {
                listOf(
                    it.name, it.sku, it.category, it.location, it.unit,
                    it.quantity, it.minQuantity, it.alertLevel(threshold), status(it),
                    it.unitCost, it.stockValue(), it.note, it.id, fmt.format(Date(it.createdAt))
                )
            },
            widths = listOf(30, 18, 18, 18, 8, 10, 15, 15, 15, 11, 13, 30, 9, 20),
            highlightRows = stockSorted.indices.filter { status(stockSorted[it]) != "OK" }.toSet()
        )

        // 3) Low stock only
        val lowItems = stockSorted.filter { it.isLow(threshold) || it.isOut() }
        val low = XlsxWriter.Sheet(
            name = ReportFormat.SHEET_LOW,
            headers = listOf(
                ReportFormat.H_ITEM, ReportFormat.H_SKU, ReportFormat.H_CATEGORY, ReportFormat.H_LOCATION,
                ReportFormat.H_QTY, ReportFormat.H_USED_ALERT, "Missing to reach alert level", ReportFormat.H_STATUS
            ),
            rows = lowItems.map {
                listOf(
                    it.name, it.sku, it.category, it.location, it.quantity, it.alertLevel(threshold),
                    (it.alertLevel(threshold) - it.quantity).coerceAtLeast(0), status(it)
                )
            },
            widths = listOf(30, 18, 18, 18, 10, 15, 26, 15)
        )

        // 4) Activity log (newest first, same as in the app)
        val activity = XlsxWriter.Sheet(
            name = ReportFormat.SHEET_LOG,
            headers = listOf(
                ReportFormat.H_WHEN, ReportFormat.H_USER, ReportFormat.H_ACTION, ReportFormat.H_ITEM,
                ReportFormat.H_CHANGE, ReportFormat.H_AFTER, ReportFormat.H_NOTE, ReportFormat.H_ITEM_ID
            ),
            rows = log.take(ReportFormat.MAX_LOG_ROWS).map {
                listOf(
                    fmt.format(Date(it.timestamp)), it.userName, actionText(it.type),
                    it.itemName, it.change, it.quantityAfter, it.note, it.itemId
                )
            },
            widths = listOf(20, 16, 14, 30, 9, 15, 40, 9)
        )

        // 5) Users (the built-in Admin account is not listed)
        val userSheet = XlsxWriter.Sheet(
            name = ReportFormat.SHEET_USERS,
            headers = listOf(ReportFormat.H_USER),
            rows = users.filterNot { it.isAdminAccount() }.map { listOf(it.name) },
            widths = listOf(28)
        )

        // 6) Categories (so empty categories survive a restore too)
        val allCategories = (categories + items.map { it.category.trim() })
            .filter { it.isNotEmpty() }
            .distinctBy { it.lowercase() }
            .sortedBy { it.lowercase() }
        val categorySheet = XlsxWriter.Sheet(
            name = ReportFormat.SHEET_CATEGORIES,
            headers = listOf(ReportFormat.H_CATEGORY),
            rows = allCategories.map { listOf(it) },
            widths = listOf(28)
        )

        return XlsxWriter.build(listOf(summary, stock, low, activity, userSheet, categorySheet))
    }

    fun actionText(type: String): String = when (type) {
        ActionType.CHECK_IN -> "Check in"
        ActionType.CHECK_OUT -> "Check out"
        ActionType.ITEM_ADDED -> "Item added"
        ActionType.ITEM_EDITED -> "Item edited"
        ActionType.ITEM_REMOVED -> "Item removed"
        else -> type
    }

    /** Reverse of [actionText], used when restoring. */
    fun typeFromText(text: String): String =
        listOf(
            ActionType.CHECK_IN, ActionType.CHECK_OUT, ActionType.ITEM_ADDED,
            ActionType.ITEM_EDITED, ActionType.ITEM_REMOVED
        ).firstOrNull { actionText(it).equals(text.trim(), ignoreCase = true) } ?: ActionType.ITEM_EDITED
}
